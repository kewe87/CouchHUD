// Pairing page for the phone remote: a big QR code and what the phone can do.

import { api } from '../core/api.js';
import { el } from '../core/dom.js';
import { attempt } from '../core/feedback.js';
import { currentView, render } from '../core/nav.js';
import { t } from '../core/i18n.js';

export function pairingPage() {
  return {
    id: 'pairing',
    get name() { return t('phone.title'); },
    info: null,
    async load(newCode = false) {
      this.info = (await attempt(() => api.getRemote(newCode), t('phone.unavailable'))) ?? { enabled: false };
      if (currentView() === this) render();
    },
    build(root) {
      if (!this.info) {
        this.load();
        root.append(el('p', { className: 'empty-note', textContent: t('phone.loading') }));
        return;
      }
      const r = this.info;
      const qr = el('div', { className: 'pair-qr' });
      if (r.qr) qr.innerHTML = r.qr; // SVG generated by the host from our own URL
      root.append(el('div', { className: 'pairing' },
        r.qr ? qr : el('div', { className: 'pair-qr pair-off', textContent: r.enabled ? t('phone.noNetwork') : t('phone.off') }),
        el('div', { className: 'pair-text' },
          el('h2', { textContent: t('phone.heading') }),
          el('ol', { className: 'pair-steps' },
            el('li', { textContent: t('phone.step1') }),
            el('li', { textContent: t('phone.step2') }),
            el('li', { textContent: t('phone.step3') })),
          r.code ? el('p', { className: 'meta pair-code', textContent: t('phone.code', { code: r.code, address: r.address }) }) : null,
          el('p', { className: 'meta', textContent: r.devices?.length ? t('phone.paired', { names: r.devices.map((d) => d.name).join(', ') }) : t('phone.noneYet') }))));
    },
    handle(action) {
      if (action === 'x') this.load(true);
    },
    hints() {
      return [['X', t('phone.hint.newCode')], ['B', t('phone.hint.back')]];
    }
  };
}
