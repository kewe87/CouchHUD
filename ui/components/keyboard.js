// On-screen keyboard for the controller. A physical keyboard works too: typed
// characters go straight into the field while the keyboard page is open.

import { api } from '../core/api.js';
import { el, setFocused } from '../core/dom.js';
import { push, render, removePage, renderHints } from '../core/nav.js';
import { state } from '../core/state.js';
import { sound } from '../sound.js';
import { toast } from '../core/feedback.js';
import { lang, t } from '../core/i18n.js';
import { clampPaste, remoteView } from '../core/paste.js';

const LAYOUTS_DE = {
  letters: [
    ['1', '2', '3', '4', '5', '6', '7', '8', '9', '0', '\u00df'],
    ['q', 'w', 'e', 'r', 't', 'z', 'u', 'i', 'o', 'p', '\u00fc'],
    ['a', 's', 'd', 'f', 'g', 'h', 'j', 'k', 'l', '\u00f6', '\u00e4'],
    ['⇧', 'y', 'x', 'c', 'v', 'b', 'n', 'm', ',', '.', '-'],
    ['?123', '@', 'space', '⌫', 'done']
  ],
  symbols: [
    ['!', '"', '§', '$', '%', '&', '/', '(', ')', '=', '?'],
    ['+', '*', '#', "'", '~', '<', '>', '|', '\\', '{', '}'],
    [':', ';', '_', '[', ']', '^', '°', '€', '`', '´', '²'],
    ['https://', 'www.', '.de', '.com', '.net', '.org', ':\\', '\\'],
    ['ABC', '@', 'space', '⌫', 'done']
  ]
};

// English uses QWERTY; German stays QWERTZ with umlauts. Symbols are the same.
const LETTERS_EN = [
  ['1', '2', '3', '4', '5', '6', '7', '8', '9', '0'],
  ['q', 'w', 'e', 'r', 't', 'y', 'u', 'i', 'o', 'p'],
  ['a', 's', 'd', 'f', 'g', 'h', 'j', 'k', 'l', "'"],
  ['⇧', 'z', 'x', 'c', 'v', 'b', 'n', 'm', ',', '.', '-'],
  ['?123', '@', 'space', '⌫', 'done']
];
const layouts = () => (lang() === 'en' ? { ...LAYOUTS_DE, letters: LETTERS_EN } : LAYOUTS_DE);

const labels = () => ({ space: t('keyboard.key.space'), done: t('keyboard.key.done'), '⌫': t('keyboard.key.delete'), paste: t('keyboard.key.paste') });

// The phone remote types into whatever keyboard is open right now.
let active = null;
let remoteListening = false;

function report(page, open) {
  api.keyboardState?.({ open, title: page?.title ?? '', ...remoteView(page) })?.catch?.(() => {});
}

function listenToPhone() {
  if (remoteListening) return;
  remoteListening = true;
  api.onRemote?.((event) => {
    if (event?.type !== 'text') return;
    if (!active) return toast(t('keyboard.noField'));
    // The phone link is plain HTTP in the LAN: never for passwords.
    if (active.secret) return toast(t('keyboard.noPasswordPhone'));
    active.text = event.text;
    active.pasted = false;
    active.update();
    sound.select();
    if (event.submit) active.submit();
  });
}

/** QR code and hint on the right: type (or paste an API key) on the phone instead. */
function phonePanel() {
  const panel = el('aside', { className: 'osk-phone' }, el('p', { className: 'osk-phone-hint', textContent: t('keyboard.phoneLoading') }));
  api.getRemote?.().then((r) => {
    if (!r?.enabled) {
      panel.replaceChildren(el('span', { className: 'osk-phone-icon', textContent: '📱' }),
        el('p', { className: 'osk-phone-hint', textContent: t('keyboard.phoneOff') }));
      return;
    }
    const qr = el('div', { className: 'osk-qr' });
    if (r.qr) qr.innerHTML = r.qr; // SVG generated by the host from our own URL
    panel.replaceChildren(
      qr,
      el('strong', { textContent: t('keyboard.phoneTitle') }),
      el('p', { className: 'osk-phone-hint', textContent: r.devices?.length ? t('keyboard.phonePaired', { devices: r.devices.map((d) => d.name).join(', '), address: r.address ?? '' }) : t('keyboard.phoneScan') }));
  }).catch(() => panel.remove());
  return panel;
}

/**
 * Opens the keyboard as a page. Resolves to the entered text, or undefined if cancelled.
 * options: { title, value, placeholder, secret, hint, maxLength, paste }
 * paste: a "Paste from PC" key (and Ctrl+V) for tokens, keys and long addresses: the host reads the clipboard (text only, trimmed, at
 * most 4096 characters, never logged; refused while the couch is locked).
 */
export function openKeyboard({ title = t('keyboard.title'), value = '', placeholder = '', secret = false, hint = '', maxLength = 0, paste = false, web = false } = {}) {
  return new Promise((resolve) => {
    let settled = false;
    const finish = (result) => {
      if (settled) return;
      settled = true;
      window.removeEventListener('keydown', onKey, true);
      if (active === page) active = null;
      report(null, false);
      resolve(result);
    };

    const page = {
      id: 'keyboard',
      name: t('keyboard.name'),
      text: value,
      title,
      secret,
      layout: 'letters',
      shift: false,
      /** Navigated with arrow keys (remote, controller in keyboard mode): Enter presses the marked key. */
      arrowNav: false,
      row: 1,
      col: 0,
      captures: (action) => action === 'lb' || action === 'rb' || action === 'start',
      onClose: () => finish(undefined),
      build(root) {
        const rows = paste ? [...layouts()[this.layout], ['paste']] : layouts()[this.layout];
        this.row = Math.min(this.row, rows.length - 1);
        this.col = Math.min(this.col, rows[this.row].length - 1);

        this.field = el('div', { className: 'osk-field' });
        this.keys = rows.map((row) =>
          row.map((key) => el('button', {
            className: `osk-key${key.length > 1 || labels()[key] ? ' osk-wide' : ''}${key === 'space' || key === 'paste' ? ' osk-space' : ''}${key === 'done' ? ' osk-done' : ''}`,
            tabIndex: -1,
            textContent: this.label(key),
            dataset: { key }
          })));
        this.board = el('div', { className: 'osk-board' }, this.keys.map((row) => el('div', { className: 'osk-row' }, row)));

        root.append(el('div', { className: 'osk-wrap' },
          // A web page's prompt: the web's frame, never the look of CouchHUD's own questions.
          el('div', { className: web ? 'osk web' : 'osk' },
            el('h2', { className: 'osk-title', textContent: title }),
            this.field,
            hint ? el('p', { className: 'osk-hint', textContent: hint }) : null,
            this.board),
          secret ? el('aside', { className: 'osk-phone' }, el('span', { className: 'osk-phone-icon', textContent: '🔒' }), el('p', { className: 'osk-phone-hint', textContent: t('keyboard.secretNote') })) : phonePanel()));
        this.update();
      },
      label(key) {
        const special = labels()[key];
        if (special) return special;
        return this.shift && key.length === 1 ? key.toUpperCase() : key;
      },
      update() {
        if (maxLength && this.text.length > maxLength) this.text = this.text.slice(0, maxLength);
        const shown = secret ? '•'.repeat(this.text.length) : this.text;
        // The caret sits where typing starts: before the placeholder, after the text.
        this.field.replaceChildren(...(this.text
          ? [el('span', { textContent: shown }), el('span', { className: 'osk-caret' })]
          : [el('span', { className: 'osk-caret' }), el('span', { className: 'osk-placeholder', textContent: placeholder })]));
        setFocused(this.keys.flat(), this.keys.slice(0, this.row).flat().length + this.col);
        for (const btn of this.keys.flat()) {
          if (btn.dataset.key === '⇧') btn.classList.toggle('active', this.shift);
        }
        report(this, true);
      },
      relabel() {
        for (const btn of this.keys.flat()) btn.textContent = this.label(btn.dataset.key);
      },
      press(key) {
        if (key !== 'paste' && key !== 'done') this.pasted = false;
        switch (key) {
          case '⇧':
            this.shift = !this.shift;
            this.relabel();
            break;
          case '?123':
          case 'ABC':
            this.layout = this.layout === 'letters' ? 'symbols' : 'letters';
            render();
            return;
          case 'space':
            this.text += ' ';
            break;
          case '⌫':
            this.text = this.text.slice(0, -1);
            break;
          case 'done':
            return this.submit();
          case 'paste':
            return this.pasteFromPc();
          default:
            this.text += this.shift && key.length === 1 ? key.toUpperCase() : key;
            // Like phone keyboards: shift applies to one letter.
            if (this.shift && key.length === 1) {
              this.shift = false;
              this.relabel();
            }
        }
        sound.move();
        this.update();
      },
      /** The PC's clipboard into the field (replacing what is there), through the host. */
      async pasteFromPc() {
        let answer;
        try {
          answer = await api.readClipboard();
        } catch (err) {
          sound.bump();
          return toast(err?.message ?? t('keyboard.pasteFailed'));
        }
        if (!answer?.ok) {
          sound.bump();
          return toast(answer?.reason ?? t('keyboard.pasteFailed'));
        }
        this.text = clampPaste(answer.text, maxLength);
        // Hidden from the remote and the phone until it is edited by hand.
        this.pasted = true;
        sound.select();
        this.update();
      },
      submit() {
        const result = this.text;
        removePage(this);
        sound.select();
        render();
        finish(result);
      },
      /** Up/down picks the key closest to the current one horizontally. */
      moveVertical(delta) {
        const target = this.row + delta;
        if (target < 0 || target >= this.keys.length) return sound.bump();
        const current = this.keys[this.row][this.col].getBoundingClientRect();
        const center = current.left + current.width / 2;
        let best = 0;
        let bestDistance = Infinity;
        this.keys[target].forEach((btn, i) => {
          const r = btn.getBoundingClientRect();
          const d = Math.abs(r.left + r.width / 2 - center);
          if (d < bestDistance) {
            bestDistance = d;
            best = i;
          }
        });
        this.row = target;
        this.col = best;
        sound.move();
        this.update();
      },
      handle(action) {
        const row = this.keys[this.row];
        switch (action) {
          case 'left':
          case 'right': {
            const next = this.col + (action === 'left' ? -1 : 1);
            if (next < 0 || next >= row.length) return sound.bump();
            this.col = next;
            sound.move();
            return this.update();
          }
          case 'up': return this.moveVertical(-1);
          case 'down': return this.moveVertical(1);
          case 'a': return this.press(row[this.col].dataset.key);
          case 'x': return this.press('⌫');
          case 'y': return this.press('space');
          case 'lb': return this.press('⇧');
          case 'rb': return this.press(this.layout === 'letters' ? '?123' : 'ABC');
          case 'start': return this.submit();
        }
      },
      pointer(node, index) {
        this.row = [...this.board.children].indexOf(node.parentElement);
        this.col = index;
        this.press(node.dataset.key);
      },
      hints() {
        // A real keyboard types directly; X/Y/LB/RB only exist on the controller.
        if (state.inputSource === 'keyboard') return [['⌨', t('keyboard.hint.typeDirect')], ['⌫', t('keyboard.hint.delete')], ['Enter', this.arrowNav ? t('keyboard.hint.pressKey') : t('keyboard.hint.done')], ...(this.arrowNav ? [[t('keyboard.hint.ctrlEnter'), t('keyboard.hint.done')]] : []), ['Esc', t('keyboard.hint.cancel')]];
        return [['A', t('keyboard.hint.type')], ['X', t('keyboard.hint.delete')], ['Y', t('keyboard.hint.space')], ['LB', t('keyboard.hint.shift')], ['RB', t('keyboard.hint.symbols')], ['≡', t('keyboard.hint.done')], ['B', t('keyboard.hint.cancel')]];
      }
    };

    // Typing on a real keyboard goes straight into the field: letters type, Backspace deletes,
    // Enter finishes, Escape cancels (that one falls through to the normal "back").
    function onKey(e) {
      if (state.stack.at(-1) !== page || state.overlay) return;
      if (e.key.startsWith('Arrow')) {
        // Remotes and controllers in keyboard mode send arrows + Enter: from now on Enter presses the marked key.
        if (!page.arrowNav) {
          page.arrowNav = true;
          renderHints();
        }
        return;
      }
      if (e.key === 'Enter') {
        e.preventDefault();
        e.stopImmediatePropagation();
        return page.arrowNav && !e.ctrlKey ? page.press(page.keys[page.row][page.col].dataset.key) : page.submit();
      }
      if (paste && e.ctrlKey && (e.key === 'v' || e.key === 'V')) {
        e.preventDefault();
        e.stopImmediatePropagation();
        return page.pasteFromPc();
      }
      if (e.key === 'Backspace') {
        e.preventDefault();
        e.stopImmediatePropagation();
        page.text = page.text.slice(0, -1);
        page.pasted = false;
        return page.update();
      }
      if (e.key.length === 1 && !e.ctrlKey && !e.altKey && !e.metaKey) {
        e.preventDefault();
        e.stopImmediatePropagation();
        // Typing letters: Enter means "done" again.
        if (page.arrowNav) {
          page.arrowNav = false;
          renderHints();
        }
        page.text += e.key;
        page.pasted = false;
        page.update();
      }
    }
    window.addEventListener('keydown', onKey, true);

    listenToPhone();
    active = page;
    push(page);
  });
}
